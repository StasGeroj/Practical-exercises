'''Дано целое число N (> 0). Найти сумму N2 + (N + 1)2 + (N + 2)2 + ... + (2N)2'''

n = int(input("введите числло n (n > 1):"))

if n <= 0: 
    print("Ошибка введите число больше 0 ")

s = n
sum = 0

while s <= 2 * n:
    sum += s ** 2
    s += 1

print(f"Сумма квадратов от {n}^2 до {2*n}^2 равна:{sum}")

